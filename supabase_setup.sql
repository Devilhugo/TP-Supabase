-- Row Level Security
alter table public.client enable row level security;
alter table public.adresse enable row level security;

-- Lecture réservée aux utilisateurs connectés.
-- (Le TP utilise "to public" : n'importe qui ayant l'URL + la clé anon
--  pourrait alors lire les clients sans se connecter.)
create policy "Lecture clients (connectés)"
  on public.client for select to authenticated using (true);

create policy "Lecture adresses (connectés)"
  on public.adresse for select to authenticated using (true);
